package variablesyconstantes;

public class variablesAndConstantes {
    public static void main(String[]args){

            //VARIABLES//

        String name = "Diego";
        name = "Vera"; // aca lo cambiamos el "valor" de la variable

        System.out.println(name);

        int age = 28;
        System.out.println(age);

        double peso = 75.8;
        System.out.println(peso);

              //CONSTANTES//

        final String EMAIL = "Diegovera1478@gamil.com";
        System.out.println(EMAIL);
        






    }
}
